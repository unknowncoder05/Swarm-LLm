"""Generate ~/.config/goose/config.yaml pointing at the swarm endpoint."""
import json, os, sys, urllib.request

env = {}
try:
    for line in open(".env"):
        line = line.strip()
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip()
except FileNotFoundError:
    print("ERROR: .env not found — run 'make init' first", file=sys.stderr)
    sys.exit(1)

key = env.get("CONSUMER_KEY")
if not key:
    print("ERROR: CONSUMER_KEY missing from .env", file=sys.stderr)
    sys.exit(1)

live_model = None
try:
    req = urllib.request.Request(
        "http://localhost:8081/swarm/api/v1/models",
        headers={"X-API-Key": key},
    )
    data = json.loads(urllib.request.urlopen(req, timeout=3).read())
    models = [m["id"] for m in data.get("data", [])]
    # Prefer agentic models in priority order
    for preferred in ("qwen3.6:27b", "devstral-small-2:24b", "devstral:24b", "gemma4:12b", "qwen3:30b-a3b", "qwen3:14b", "qwen3:8b", "ministral-3:8b"):
        if preferred in models:
            live_model = preferred
            break
    if not live_model and models:
        live_model = models[0]
except Exception:
    pass

model = live_model or "devstral:24b"

config = f"""# Goose configuration — auto-generated by make goose-setup
# Edit GOOSE_MODEL to switch models; available: any model live on the swarm.
GOOSE_PROVIDER: openai
GOOSE_MODEL: {model}

extensions:
  developer:
    enabled: true
    type: platform
    name: developer
    description: Write and edit files, and execute shell commands
    display_name: Developer
    bundled: true
  todo:
    enabled: false
    type: platform
    name: todo
    display_name: Todo
    bundled: true
  apps:
    enabled: false
    type: platform
    name: apps
    display_name: Apps
    bundled: true
  analyze:
    enabled: false
    type: platform
    name: analyze
    display_name: Analyze
    bundled: true
  extensionmanager:
    enabled: false
    type: platform
    name: Extension Manager
    display_name: Extension Manager
    bundled: true
  summon:
    enabled: false
    type: platform
    name: summon
    display_name: Summon
    bundled: true
  tom:
    enabled: false
    type: platform
    name: tom
    display_name: Top Of Mind
    bundled: true
  scheduler:
    enabled: false
    type: platform
    name: scheduler
    display_name: Scheduler
    bundled: true
  skills:
    enabled: false
    type: platform
    name: skills
    display_name: Skills
    bundled: true
  computercontroller:
    enabled: false
    type: builtin

providers:
  openai:
    base_url: https://sandbox.yerson.co/swarm/api/v1
    api_key: {key}

# Environment variables (picked up by goose at runtime)
OPENAI_BASE_URL: https://sandbox.yerson.co/swarm/api/v1
OPENAI_API_KEY: {key}
"""

out = os.path.expanduser("~/.config/goose/config.yaml")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write(config)

status = f"default model → {model}" + ("  (live)" if live_model else "  (no agents online, update after connecting one)")
print(f"~/.config/goose/config.yaml written  [{status}]")
